from __future__ import annotations

from typing import Any

import numpy as np


def sw_checks(name: str, param: Any) -> None:
    """Validates parameters following rSWeeP SW.checks contracts."""
    if name == "seqtype":
        valid_opts = ("AA", "NT")
        if not isinstance(param, str) or param not in valid_opts:
            msg = f"'seqtype' should be any one of the options: \n {', '.join(valid_opts)}"
            raise ValueError(msg)

    elif name == "extension":
        if not isinstance(param, (str, list, tuple)):
            msg = "'extension' should be a character or a list of characters.\n"
            raise ValueError(msg)

    elif name == "psz":
        if (
            not isinstance(param, (int, np.integer))
            or isinstance(param, bool)
            or (isinstance(param, float) and not param.is_integer())
        ):
            msg = "'psz' should be a integer numeric value.\n"
            raise ValueError(msg)

    elif name == "mask":
        if not isinstance(param, (list, tuple, np.ndarray)) or len(param) == 0:
            msg = "'mask' should be a vector as: mask = c(2,1,2). See help of function.\n"
            raise ValueError(msg)

    elif name in (
        "bin",
        "readEachFASTA",
        "read_each_fasta",
        "lowRAMmode",
        "low_ram_mode",
        "RNAseqdata",
        "rna_seq_data",
        "transpose",
        "concatenate",
    ):
        if not isinstance(param, bool):
            flag_name = "lowRAMmode" if "ram" in name.lower() or "fasta" in name.lower() else name
            msg = f"'{flag_name}' should be logical. TRUE or FALSE.\n"
            raise ValueError(msg)

    elif name == "ncores":
        if param is not None and (
            not isinstance(param, (int, np.integer)) or isinstance(param, bool) or int(param) <= 0
        ):
            msg = "'ncores' should be a positive integer or NULL.\n"
            raise ValueError(msg)

    elif name in ("fastalist", "fasta_list"):
        if not isinstance(param, (list, tuple)) or len(param) == 0:
            msg = (
                "The folder provided does not seem to contain files with the extension provided, "
                "or it is empty. \n"
            )
            raise ValueError(msg)

    elif name == "norm":
        valid_norms = ("none", "log", "Neg", "logNeg")
        if not isinstance(param, str) or param not in valid_norms:
            msg = (
                "'norm' must be one of the following options: `none` for none of normalization "
                "options, `log` for logarithm, `Neg` for conversion of nulls to -1 or `logNeg` "
                "for logarithm and conversion of nulls to -1. \n"
            )
            raise ValueError(msg)


def sw_check_orthbase(orth: Any, input_data: Any) -> None:
    """Validates that orthbase is a 2D matrix matching the features of input_data."""
    if not hasattr(orth, "shape") or len(orth.shape) != 2:
        msg = "Orthbase must be an array generated by the `orthBase' function. See ?orthBase"
        raise ValueError(msg)

    if not hasattr(input_data, "shape") or len(input_data.shape) != 2:
        msg = "Input data must be a 2D array or matrix."
        raise ValueError(msg)

    if orth.shape[0] != input_data.shape[1]:
        msg = (
            "The number of rows of the orthbase matrix must be equal to the number of features "
            "of the input data. See ?orthBase"
        )
        raise ValueError(msg)
